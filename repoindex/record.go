package repoindex

import (
	"crypto/sha256"
	"path"
	"strings"

	"github.com/georgejieh/open-trestle/internal/varcodec"
	"github.com/georgejieh/open-trestle/syntaxanalysis"
)

// Key names one stored analysis: a blob analysed as one language. A C or
// C++ header is analysed under rules of its own, so the key also says
// whether the path is a header.
type Key [32]byte

func recordKey(algorithm, object string, language syntaxanalysis.Language, filePath string) Key {
	header := ""
	switch strings.ToLower(path.Ext(filePath)) {
	case ".h", ".hh", ".hpp", ".hxx":
		header = "header"
	}
	return sha256.Sum256([]byte("blob\x00" + algorithm + "\x00" + object + "\x00" + string(language) + "\x00" + header))
}

// blobRecord is what the index keeps of one analysed blob. A binary blob
// has no analysis.
type blobRecord struct {
	binary, generated bool
	size              int64
	analysis          []byte
}

const (
	flagBinary    byte = 1
	flagGenerated byte = 2
	recordFlags        = flagBinary | flagGenerated
)

func (r blobRecord) flags() byte {
	flags := byte(0)
	if r.binary {
		flags |= flagBinary
	}
	if r.generated {
		flags |= flagGenerated
	}
	return flags
}

func (r blobRecord) encode() []byte {
	out := varcodec.AppendUvarint([]byte{r.flags()}, uint64(r.size))
	return append(out, r.analysis...)
}

func decodeBlobRecord(data []byte) (blobRecord, error) {
	r := varcodec.NewReader(data)
	flags := r.Byte()
	size := r.Uvarint()
	if r.Err() != nil || flags > recordFlags || size > 1<<40 {
		return blobRecord{}, errCorrupt
	}
	record := blobRecord{binary: flags&flagBinary != 0, generated: flags&flagGenerated != 0, size: int64(size), analysis: r.Fixed(r.Len())}
	if record.binary != (len(record.analysis) == 0) {
		return blobRecord{}, errCorrupt
	}
	return record, nil
}

// decode decodes the analysis of the record for a path.
func (r blobRecord) decode(filePath string) (syntaxanalysis.FileAnalysis, error) {
	analysis, err := syntaxanalysis.DecodeBinary(r.analysis, filePath)
	if err != nil {
		return syntaxanalysis.FileAnalysis{}, errCorrupt
	}
	return analysis, nil
}
