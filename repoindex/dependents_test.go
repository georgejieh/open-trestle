func TestDependentsFollowReferenceCandidatesBackwards(t *testing.T) {
	analyzer := realAnalyzer(t)
	repo := newGitRepository(t)
	repo.write(fixtureFiles)
	baseCommit := repo.commit("base")
	head := fixtureFiles["calc/calc.go"]
	head = strings.Replace(head, "return a + b", "return b + a", 1)
	head = strings.Replace(head, "\nfunc unexported() int { return Add(1, 2) }\n", "", 1)
	repo.write(map[string]string{"calc/calc.go": head})
	headCommit := repo.commit("head")
	store := newTestStore(t, DefaultStoreLimits())
	base := loadGraph(t, store, buildCommit(t, store, analyzer, repo.tree(baseCommit)))
	headGraph := loadGraph(t, store, buildCommit(t, store, analyzer, repo.tree(headCommit)))

	changes := []Change{{Path: "calc/calc.go", BasePath: "calc/calc.go", HeadLines: []LineRange{{4, 4}}, BaseLines: []LineRange{{4, 4}, {10, 10}}}}
	result := Dependents(headGraph, base, changes, DefaultDependentsLimits())
	got := []string{}
	for _, c := range result.Changed {
		got = append(got, c.Side+" "+c.QualifiedName.Untrusted())
	}
	for _, d := range result.Dependents {
		name := "<top>"
		if d.Symbol != nil {
			name = d.Symbol.QualifiedName.Untrusted()
		}
		got = append(got, fmt.Sprintf("%d %s %s via %s %s", d.Depth, d.Path, name, d.Via.Untrusted(), d.Scope))
	}
	want := []string{
		"head Add",
		"base unexported",
		"1 calc/calc.go Push via Add file",
		"1 calc/calc_test.go TestAdd via Add package",
		"1 cmd/app/main.go run via Add import",
		"2 cmd/app/main.go main via run file",
	}
	if strings.Join(got, "\n") != strings.Join(want, "\n") {
		t.Fatalf("dependents:\n%s", strings.Join(got, "\n"))
	}
	if fmt.Sprint(result.TestFiles) != "[calc/calc_test.go]" || len(result.Files) != 3 || result.Cut != (DependentsCut{}) {
		t.Fatalf("files %v tests %v cut %+v", result.Files, result.TestFiles, result.Cut)
	}

	cut := Dependents(headGraph, base, changes, DependentsLimits{MaxDepth: 1, MaxDependents: 2, MaxCandidates: 100})
	if len(cut.Dependents) != 2 || cut.Cut.DependentsDropped != 1 || cut.Cut.NotExpanded != 2 {
		t.Fatalf("limited dependents = %d, cut %+v", len(cut.Dependents), cut.Cut)
	}

	missing := Dependents(headGraph, nil, []Change{{Path: "README.md", HeadLines: []LineRange{{1, 1}}}, {Path: "gone.go", BasePath: "gone.go", BaseLines: []LineRange{{1, 1}}}}, DefaultDependentsLimits())
	if len(missing.Gaps) != 2 || missing.Gaps[0].Reason != string(StatusNotAnalysed) || missing.Gaps[1].Reason != "base_not_loaded" {
		t.Fatalf("gaps = %+v", missing.Gaps)
	}
}

func TestClassifyPath(t *testing.T) {
	for path, want := range map[string]Role{
		"main.go": RoleSource, "a/b_test.go": RoleTest, "src/app.test.ts": RoleTest, "tests/x.py": RoleTest,
		"pkg/test_x.py": RoleTest, "spec/a_spec.rb": RoleTest, "src/FooTest.java": RoleTest, "lib/testdata/f.go": RoleTest,
		"vendor/a/b.go": RoleVendored, "web/node_modules/x/i.js": RoleVendored, "third_party/z.c": RoleVendored,
		"api.pb.go": RoleGenerated, "go.sum": RoleGenerated, "app.min.js": RoleGenerated, "flake.lock": RoleGenerated,
		"README.md": RoleDocs, "LICENSE": RoleDocs, "docs/guide.html": RoleDocs, "docs/img.png": RoleDocs,
		"go.mod": RoleConfig, "Makefile": RoleConfig, "CMakeLists.txt": RoleConfig, ".github/workflows/ci.yml": RoleConfig,
		"tsconfig.base.json": RoleConfig, "image.png": RoleOther, "docs/example.go": RoleSource,
	} {
		if got := ClassifyPath(path); got != want {
			t.Errorf("%s = %s, want %s", path, got, want)
		}
	}
	if !isGeneratedContent([]byte("// Code generated by x. DO NOT EDIT.\npackage a")) || !isGeneratedContent([]byte("/* @generated */")) || isGeneratedContent([]byte("package a // generated")) {
		t.Fatal("generated markers")
	}
	if !isBinaryContent([]byte("a\x00b")) || isBinaryContent([]byte("text")) {
		t.Fatal("binary detection")
	}
}
